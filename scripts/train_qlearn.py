"""Tabular Q-learning (or SARSA) on a single fixed map.
Usage: python scripts/train_qlearn.py --size 6 --episodes 20000 --seed 0 [--sarsa]

The fixed map is the map generated by RoverEnv.reset(seed=--map-seed). Evaluation is greedy, on that same map, over many
episodes (slip is still random), so the numbers measure how well the Q-table solved THIS map -- they are not comparable
to PPO/DQN, which are evaluated on unseen random maps.
"""
import argparse
import json
from pathlib import Path

import numpy as np

from rover.env import RoverEnv
from rover.qlearn import QConfig, QTableAgent, state_of


def fixed_map(map_seed: int, **env_kw) -> np.ndarray:
    env = RoverEnv(**env_kw)
    env.reset(seed=map_seed)
    return env.grid.copy()


def evaluate_fixed(agent: QTableAgent, grid: np.ndarray, episodes: int = 200, seed: int = 20_000, **env_kw) -> dict:
    env = RoverEnv(fixed_map=grid, **env_kw)
    outcomes, steps, returns = [], [], []
    for e in range(episodes):
        env.reset(seed=seed + e)
        done, ret, t = False, 0.0, 0
        while not done:
            _, r, term, trunc, info = env.step(agent.greedy(state_of(env)))
            ret, t, done = ret + r, t + 1, term or trunc
        outcomes.append(info["outcome"]); steps.append(t); returns.append(ret)
    n = len(outcomes)
    return {"success": outcomes.count("success") / n, "crater": outcomes.count("crater") / n,
            "battery": outcomes.count("battery") / n, "timeout": outcomes.count("timeout") / n,
            "mean_steps": float(np.mean(steps)), "mean_return": float(np.mean(returns))}


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--episodes", type=int, default=20_000)
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--map-seed", type=int, default=10_000, help="seed that generates the fixed map")
    p.add_argument("--p-slip", type=float, default=0.30)
    p.add_argument("--b0", type=int, default=15)
    p.add_argument("--size", type=int, default=10)
    p.add_argument("--alpha", type=float, default=0.1)
    p.add_argument("--gamma", type=float, default=0.99)
    p.add_argument("--eps-end", type=float, default=0.05)
    p.add_argument("--eps-decay-frac", type=float, default=0.5)
    p.add_argument("--q-init", type=float, default=0.0)
    p.add_argument("--sarsa", action="store_true", help="on-policy SARSA instead of Q-learning")
    p.add_argument("--eval-episodes", type=int, default=200)
    p.add_argument("--eval-every", type=int, default=1000)
    p.add_argument("--out", default="runs")
    a = p.parse_args()

    env_kw = dict(p_slip=a.p_slip, b0=a.b0, size=a.size)
    grid = fixed_map(a.map_seed, **env_kw)
    env = RoverEnv(fixed_map=grid, **env_kw)
    agent = QTableAgent(a.size, env.b_max, QConfig(alpha=a.alpha, gamma=a.gamma, eps_end=a.eps_end,
                                                   eps_decay_frac=a.eps_decay_frac, q_init=a.q_init, sarsa=a.sarsa),
                        seed=a.seed)
    out = Path(a.out) / f"{'sarsa' if a.sarsa else 'qlearn'}_seed{a.seed}"; out.mkdir(parents=True, exist_ok=True)
    (out / "config.json").write_text(json.dumps(vars(a), indent=1))
    np.save(out / "fixed_map.npy", grid)
    log, ep_returns, steps = [], [], 0

    for ep in range(1, a.episodes + 1):
        env.reset(seed=a.seed * 1_000_003 + ep)
        s, eps = state_of(env), agent.epsilon(ep, a.episodes)
        act, done, ret = agent.act(s, eps), False, 0.0
        while not done:
            _, r, term, trunc, _ = env.step(act)
            s2 = state_of(env)
            act2 = agent.act(s2, eps)  # drawn before the update so SARSA uses the action it will really take
            agent.update(s, act, r, s2, term, act2)
            s, act, ret, done, steps = s2, act2, ret + r, term or trunc, steps + 1
        ep_returns.append(ret)
        if ep % a.eval_every == 0 or ep == a.episodes:
            m = evaluate_fixed(agent, grid, a.eval_episodes, **env_kw)
            m.update(episode=ep, steps=steps, train_return=float(np.mean(ep_returns[-a.eval_every:])), eps=round(eps, 4))
            log.append(m)
            print(json.dumps(m))
            (out / "log.json").write_text(json.dumps(log, indent=1))
            np.save(out / "qtable.npy", agent.Q)


if __name__ == "__main__":
    main()
